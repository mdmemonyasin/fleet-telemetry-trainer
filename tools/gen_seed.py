"""Generate db/init/02_seed.sql and data/vehicles.csv deterministically.

Usage: python3 tools/gen_seed.py <repo_root>
"""
import random
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
rnd = random.Random(42)
VIN_CHARS = "ABCDEFGHJKLMNPRSTUVWXYZ0123456789"  # no I, O, Q

customers = [
    ("MegaFleet Logistics", "fleet"), ("CityRide Rentals", "rental"), ("FleetCo", "fleet"),
    ("Speedway Motors", "dealer"), ("AutoFin Capital", "lender"), ("SafeDrive Insurance", "insurer"),
    ("GreenCab EV", "fleet"), ("Highway Haulers", "fleet"), ("UrbanWheels", "rental"),
    ("Prime Auto Dealers", "dealer"), ("QuickLoan Motors", "lender"), ("OldRoute Transport", "fleet"),
]
oems = [("OEM-A", "1FA"), ("OEM-B", "2GB"), ("OEM-C", "3HC"), ("OEM-D", "5YJ")]
vehicle_counts = [80, 25, 20, 10, 10, 5, 15, 12, 8, 6, 5, 4]  # = 200; customer 1 is the big fleet

def vin_for(wmi: str) -> str:
    return wmi + "".join(rnd.choice(VIN_CHARS) for _ in range(14))

vehicles = []
for cid, n in enumerate(vehicle_counts, start=1):
    for _ in range(n):
        oem, wmi = rnd.choice(oems)
        status = "deprovisioned" if (cid == 12 or rnd.random() < 0.03) else "active"
        vehicles.append((vin_for(wmi), cid, oem, rnd.randint(2018, 2025), status))

lines = ["-- Generated by tools/gen_seed.py (seed 42). Do not edit by hand.", "BEGIN;"]
for name, typ in customers:
    status = "churned" if name == "OldRoute Transport" else "active"
    lines.append(f"INSERT INTO customers (name, type, status) VALUES ('{name}', '{typ}', '{status}');")
for vin, cid, oem, my, st in vehicles:
    lines.append(f"INSERT INTO vehicles (vin, customer_id, oem, model_year, status) VALUES ('{vin}', {cid}, '{oem}', {my}, '{st}');")

providers = ["TrackOne", "GeoBox", "OEM-Native"]
dev_id = 0
for i, (vin, cid, oem, my, st) in enumerate(vehicles):
    prov = "OEM-Native" if oem in ("OEM-A", "OEM-D") else rnd.choice(providers[:2])
    fw = f"{rnd.choice([2, 3])}.{rnd.randint(0, 9)}"
    lines.append(f"INSERT INTO devices (vin, provider, firmware, last_seen_at) VALUES ('{vin}', '{prov}', '{fw}', now() - interval '{rnd.randint(1, 600)} minutes');")
    if i % 17 == 0:  # trap: duplicate device rows for some VINs (SQL ticket U4)
        lines.append(f"INSERT INTO devices (vin, provider, firmware, last_seen_at) VALUES ('{vin}', '{prov}', '{fw}', now() - interval '{rnd.randint(601, 5000)} minutes');")
    if i % 37 == 0:  # trap: tie on last_seen_at
        lines.append(f"INSERT INTO devices (vin, provider, firmware, last_seen_at) VALUES ('{vin}', '{prov}', '{fw}', NULL);")

for i, (vin, cid, oem, my, st) in enumerate(vehicles):
    start = f"2025-{rnd.randint(1, 12):02d}-01"
    if i % 23 == 0:
        status, end = "cancelled", f"'2026-{rnd.randint(1, 9):02d}-15'"
    elif i % 29 == 0:
        status, end = "active", "NULL"      # trap: open-ended
    elif st == "deprovisioned":
        status, end = "expired", "'2026-06-30'"
    else:
        status, end = "active", f"'2026-{rnd.randint(11, 12):02d}-{rnd.randint(1, 28):02d}'"
    lines.append(f"INSERT INTO subscriptions (customer_id, vin, plan, start_date, end_date, status) VALUES ({cid}, '{vin}', '{rnd.choice(['basic', 'pro', 'enterprise'])}', '{start}', {end}, '{status}');")

# ~60k telemetry rows: 300 pings every 5 min for each active vehicle, ending 1 hour ago.
lines.append("""
INSERT INTO telemetry (vin, ts_utc, speed_kmph, odometer_km, lat, lon, heading, soc_pct, ignition, source_oem)
SELECT v.vin,
       date_trunc('minute', now()) - interval '1 hour' - (g.n * interval '5 minutes'),
       round((random() * 110)::numeric, 2),
       10000 + (300 - g.n) * 4.2 + (abs(hashtext(v.vin)) % 50000),
       12.90 + random() * 0.2,
       77.50 + random() * 0.2,
       (random() * 359)::int,
       CASE WHEN v.oem = 'OEM-D' THEN round((20 + random() * 80)::numeric, 2) END,
       true,
       v.oem
FROM vehicles v
CROSS JOIN generate_series(0, 299) AS g(n)
WHERE v.status = 'active';
""")
lines.append("ANALYZE customers, vehicles, devices, subscriptions, telemetry;")
lines.append("COMMIT;")

(root / "db" / "init").mkdir(parents=True, exist_ok=True)
(root / "db" / "init" / "02_seed.sql").write_text("\n".join(lines) + "\n")
(root / "data").mkdir(exist_ok=True)
with open(root / "data" / "vehicles.csv", "w") as f:
    f.write("vin,customer_id,oem,status\n")
    for vin, cid, oem, my, st in vehicles:
        f.write(f"{vin},{cid},{oem},{st}\n")
print(f"vehicles={len(vehicles)} active={sum(1 for v in vehicles if v[4] == 'active')}")
